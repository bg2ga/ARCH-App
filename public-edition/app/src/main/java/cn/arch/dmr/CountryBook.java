    static String countryFromCallsign(String call) {
        try {
            if (call == null) return "";
            String c = call.trim().toUpperCase(Locale.ROOT).replaceAll("[^A-Z0-9]", "");
            if (c.isEmpty()) return "";
            for (int n = Math.min(c.length(), 8); n >= 1; n--) {
                String hit = CALLSIGN_COUNTRY.get(c.substring(0, n));
                if (hit != null && !hit.isEmpty()) return clean(hit);
            }
        } catch (Throwable ignored) {}
        return "";
    }
